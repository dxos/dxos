// Generates the site's CSS variables from the brand palette, and fails on a contrast miss.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { THEMES } from '../src/theme/palette.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const vars = (theme) => ({
  '--c-bg': theme.bg,
  '--c-surface': theme.surface,
  '--c-surface-strong': theme.surfaceStrong,
  '--c-fg': theme.fg,
  '--c-muted': theme.muted,
  '--c-hairline': theme.hairline,
  '--c-hairline-strong': theme.hairlineStrong,
  '--c-accent': theme.accent,
  '--c-on-accent': theme.onAccent,
  '--c-mark': theme.mark,
  // Starlight's own variables, so its components inherit the palette without per-component overrides.
  '--sl-color-bg': theme.bg,
  '--sl-color-bg-nav': theme.bg,
  '--sl-color-bg-sidebar': theme.bg,
  '--sl-color-bg-inline-code': theme.surface,
  '--sl-color-hairline': theme.hairline,
  '--sl-color-hairline-light': theme.hairline,
  '--sl-color-hairline-shade': theme.hairline,
  '--sl-color-text': theme.fg,
  '--sl-color-text-accent': theme.accent,
  '--sl-color-text-invert': theme.onAccent,
  '--sl-color-accent': theme.accent,
  '--sl-color-accent-high': theme.accent,
  '--sl-color-accent-low': theme.surface,
  '--sl-color-white': theme.fg,
  '--sl-color-gray-1': theme.fg,
  '--sl-color-gray-2': theme.fg,
  '--sl-color-gray-3': theme.muted,
  '--sl-color-gray-4': theme.muted,
  '--sl-color-gray-5': theme.hairlineStrong,
  '--sl-color-gray-6': theme.surface,
  '--sl-color-black': theme.bg,
});

const block = (selector, values) =>
  `${selector} {\n${Object.entries(values)
    .map(([key, value]) => `  ${key}: ${value};`)
    .join('\n')}\n}\n`;

const rgb = (hex) => [1, 3, 5].map((start) => parseInt(hex.slice(start, start + 2), 16));
const luminance = (hex) => {
  const [red, green, blue] = rgb(hex).map((value) => {
    const channel = value / 255;
    return channel <= 0.03928 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * red + 0.7152 * green + 0.0722 * blue;
};
const contrast = (first, second) => {
  const [high, low] = [luminance(first), luminance(second)].sort((left, right) => right - left);
  return (high + 0.05) / (low + 0.05);
};

const checkContrast = () => {
  const failures = [];
  for (const [name, theme] of Object.entries(THEMES)) {
    const checks = [
      ['text on ground', theme.fg, theme.bg, 7],
      ['muted on ground', theme.muted, theme.bg, 4.5],
      ['muted on code', theme.muted, theme.surface, 4.5],
      ['accent on ground', theme.accent, theme.bg, 4.5],
      ['label on accent', theme.onAccent, theme.accent, 4.5],
      ['mark on ground', theme.mark, theme.bg, 3],
      ...Object.entries(theme.code).map(([token, color]) => [`code ${token}`, color, theme.surface, 4.5]),
    ];
    for (const [label, foreground, background, floor] of checks) {
      const ratio = contrast(foreground, background);
      if (ratio < floor) {
        failures.push(`${name} ${label}: ${ratio.toFixed(2)}:1, floor ${floor}:1`);
      }
    }
  }
  if (failures.length > 0) {
    throw new Error(`Contrast below floor:\n${failures.join('\n')}`);
  }
};

/** Writes `src/styles/tokens.generated.css`, after failing on any color below its contrast floor. */
export const generateTheme = () => {
  checkContrast();
  writeFileSync(
    join(root, 'src/styles/tokens.generated.css'),
    [
      '/* Generated by scripts/gen-theme.mjs. Do not edit. */\n',
      block(':root', {
        '--c-radius': '8px',
        '--c-dur': '120ms',
        '--sl-font': "'DM Sans', system-ui, sans-serif",
        '--sl-font-mono': "'DM Mono', ui-monospace, monospace",
      }),
      block(':root, :root[data-theme="dark"]', vars(THEMES.dark)),
      block(':root[data-theme="light"]', vars(THEMES.light)),
    ].join('\n'),
  );
};

/**
 * Writes `src/styles/island-base.generated.css`: Tailwind's preflight, scoped to the demos. On a Webflow page
 * the global preflight sits below the Webflow layer so the page keeps its typography; this copy sits above it, so
 * a demo, and anything it portals outside `.page-wrapper`, still gets the reset the react-ui theme expects.
 */
export const generateIslandBase = () => {
  const require = createRequire(join(root, 'node_modules/@dxos/ui-theme/package.json'));
  const preflight = readFileSync(require.resolve('tailwindcss/preflight.css'), 'utf-8')
    .replace(/^html,\n:host \{/m, ':scope {')
    .replaceAll('--theme(', 'var(');
  if (/\bhtml\b|--theme\(/.test(preflight.replace(/\/\*[\s\S]*?\*\//g, ''))) {
    throw new Error('Tailwind preflight changed shape; update generateIslandBase.');
  }

  writeFileSync(
    join(root, 'src/styles/island-base.generated.css'),
    [
      '/* Generated by scripts/gen-theme.mjs. Do not edit. */',
      '@layer island-base {',
      '@scope (.dx-island, body > :not(.page-wrapper)) {',
      preflight,
      // What the theme's `:root` gives an app, which the island cannot inherit from a Webflow page.
      ':scope {\n  font-family: var(--font-body);\n  color: var(--color-fg);\n}',
      '}',
      '}',
      '',
    ].join('\n'),
  );
};
