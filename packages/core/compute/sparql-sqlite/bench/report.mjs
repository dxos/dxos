// Renders the real-dataset results (real.mjs `query` output with and without hints, the load summaries and the
// LOCAL Oxigraph runs) into markdown: per-dataset tables on stdout, and the full SQL + plan + join-prefix appendix
// into <out dir>/plans.md. It also copies the compact JSON results to <out dir>.
//
//   node bench/report.mjs <results dir> <out dir>

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [resultsDir, outDir] = process.argv.slice(2);
mkdirSync(outDir, { recursive: true });

const DATASETS = [
  { db: 'bsbm1m', label: 'BSBM 1M (2,785 products)', oracle: 'bsbm-2785' },
  { db: 'bsbm5m', label: 'BSBM 5M (14,000 products)' },
  { db: 'lubm10', label: 'LUBM(10), no inference', oracle: 'lubm10' },
  { db: 'lubm10rdfs', label: 'LUBM(10) + RDFS closure (Jena riot --rdfs)' },
  { db: 'watdiv10', label: 'WatDiv scale 10', oracle: 'watdiv10' },
  { db: 'watdiv50', label: 'WatDiv scale 50', oracle: 'watdiv50' },
  { db: 'dblp6m', label: 'DBLP, first 6M lines of dblp.nt', oracle: 'dblp-6m' },
];

const read = (file) => (existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : undefined);
const fmt = (value, digits = 1) =>
  value === undefined || value === null || Number.isNaN(value)
    ? '-'
    : value >= 100
      ? value.toFixed(0)
      : value.toFixed(digits);
const median = (values) => {
  const sorted = values.filter((value) => value !== undefined).sort((left, right) => left - right);
  return sorted.length ? sorted[Math.floor(sorted.length / 2)] : undefined;
};

/** Short plan note: the first loop and anything that usually signals a bad plan. */
const planNote = (plan = []) => {
  const loops = plan
    .map((row) => row.replace(/^\d+\/\d+ /, ''))
    .filter((row) => /^(SCAN|SEARCH) q\d+/.test(row))
    .map((row) =>
      row
        .replace(/^SEARCH (q\d+) USING (COVERING )?INDEX quads_(\w+) \((.*)\)/, '$1 $3($4)')
        .replace(/^SEARCH (q\d+) USING PRIMARY KEY \((.*)\)/, '$1 spo($2)')
        .replace(/=\?/g, '')
        .replace(/ AND /g, ','),
    );
  const flags = [];
  if (plan.some((row) => /SCAN (main\.)?(quads|q\d+)\b(?! USING)/.test(row) || /SCAN q\d+ USING/.test(row))) {
    flags.push('full scan');
  }
  if (plan.some((row) => /BLOOM FILTER/.test(row))) {
    flags.push('bloom');
  }
  if (plan.some((row) => /AUTOMATIC/.test(row))) {
    flags.push('auto-index');
  }
  if (plan.some((row) => /MATERIALIZE terms/.test(row))) {
    flags.push('terms materialized');
  }
  if (plan.some((row) => /TEMP B-TREE/.test(row))) {
    flags.push('temp b-tree');
  }
  const order = loops.length > 4 ? `${loops.slice(0, 3).join(' -> ')} -> ...(${loops.length})` : loops.join(' -> ');
  return [order, flags.length ? `**${flags.join(', ')}**` : ''].filter(Boolean).join(' ');
};

const tables = [];
const appendix = [
  '# Real-dataset plans',
  '',
  'Generated by `bench/report.mjs`. Compiled SQL and `EXPLAIN QUERY PLAN` were captured on the deployed DO; `est` is the product of `sqlite_stat1` equality fan-outs along the plan (no filter selectivity), `actual` is a `COUNT(*)` of the join prefix run on the same DO.',
  '',
];
const summary = [];

for (const { db, label, oracle } of DATASETS) {
  const h1 = read(join(resultsDir, `q-${db}-h1.json`));
  const h0 = read(join(resultsDir, `q-${db}-h0.json`));
  const load = read(join(resultsDir, `load-${db}.json`));
  const ox = oracle ? read(join(resultsDir, `oxigraph-${oracle}.json`)) : undefined;
  if (!h1) {
    continue;
  }
  const rewrites = read(join(resultsDir, `q-${db}-rw.json`));
  if (rewrites) {
    h1.queries.push(...rewrites.queries);
  }
  const before = new Map((h0?.queries ?? []).map((query) => [query.id, query]));
  const oxById = new Map((ox?.results ?? []).map((result) => [result.id, result]));
  tables.push(`### ${label}`, '');
  tables.push(
    `Deployed \`${h1.url}\`, build \`${h1.build}\`, ${h1.at.slice(0, 16)}Z. ${h1.stats.triples.toLocaleString('en-US')} triples, ${(h1.stats.dbBytes / 1e6).toFixed(0)} MB. Ping ${fmt(h1.pingMs)} ms.`,
    '',
    '| query | kind | rows | OK | server ms | no hints | wall ms | 1st ms | Oxigraph LOCAL ms | plan (loop order; flags) |',
    '| ----- | ---- | ---: | - | --------: | -------: | ------: | -----: | ----------------: | ------------------------ |',
  );
  const servers = [];
  for (const query of h1.queries) {
    const old = before.get(query.id);
    // A rewrite (`...r`) is checked against the engine-neutral original's Oxigraph answer.
    const reference = oxById.get(query.id) ?? oxById.get(query.id.replace(/r(-.*)?$/, '$1'));
    const check = query.error
      ? ''
      : reference && !reference.error
        ? query.rows === reference.rows && query.checksum === reference.checksum
          ? 'OK'
          : query.rows === reference.rows && /\bLIMIT\b/i.test(query.sparql)
            ? '~'
            : `X (${reference.rows})`
        : '';
    if (!query.error) {
      servers.push(query.serverMs);
    }
    tables.push(
      `| ${query.id} | ${query.kind ?? query.inference ?? ''} | ${query.error ? `**${query.error.replace(/^.*?: /, '').slice(0, 60)}**` : query.rows} | ${check} | ${fmt(query.serverMs)} | ${fmt(old?.serverMs)} | ${fmt(query.wallMs, 0)} | ${fmt(query.firstMs, 0)} | ${reference?.error ? 'err' : fmt(reference?.ms)} | ${query.error ? '' : planNote(query.plan)} |`,
    );
    // One instance per template keeps the appendix readable; every instance is in the JSON.
    if (query.template && query.template !== query.id && !/a$/.test(query.id)) {
      continue;
    }
    appendix.push(`## ${db} · ${query.id}`, '', '```sparql', query.sparql.trim(), '```', '');
    if (query.sql) {
      appendix.push('```sql', query.sql, '```', '', '```', ...query.plan, '```', '');
    }
    if (query.prefix?.length) {
      appendix.push('| step | est | actual |', '| ---- | --: | -----: |');
      for (const step of query.prefix) {
        appendix.push(`| ${step.step} | ${step.estimate} | ${step.actual ?? step.error ?? ''} |`);
      }
      appendix.push('');
    }
  }
  tables.push('');
  const noHints = h0 && {
    ...h0,
    stat1: undefined,
    queries: h0.queries.map(({ id, rows, checksum, error, wallMs, serverMs, firstMs, plan }) => ({
      id,
      rows,
      checksum,
      error,
      wallMs,
      serverMs,
      firstMs,
      plan,
    })),
  };
  // Compiled SQL differs between template instances only in constant ids, so one copy per template is kept.
  const hints = {
    ...h1,
    queries: h1.queries.map((query) =>
      query.template && query.template !== query.id && !/a$/.test(query.id) ? { ...query, sql: undefined } : query,
    ),
  };
  writeFileSync(join(outDir, `${db}.json`), JSON.stringify({ load, hints, noHints, oxigraphLocal: ox }));
  summary.push({
    db,
    label,
    triples: h1.stats.triples,
    queries: h1.queries.length,
    errors: h1.queries.filter((query) => query.error).length,
    medianServer: median(servers),
    maxServer: Math.max(...servers),
    load,
  });
}

writeFileSync(join(outDir, 'plans.md'), appendix.join('\n'));
console.log('## Summary\n');
console.log(
  '| dataset | triples | queries | rejected | median server ms | max server ms | ingest quads/s | MB | B/triple |',
);
console.log(
  '| ------- | ------: | ------: | -------: | ---------------: | ------------: | -------------: | -: | -------: |',
);
for (const row of summary) {
  console.log(
    `| ${row.label} | ${row.triples.toLocaleString('en-US')} | ${row.queries} | ${row.errors} | ${fmt(row.medianServer)} | ${fmt(row.maxServer)} | ${row.load ? fmt(row.load.quadsPerSec, 0) : '-'} | ${row.load ? (row.load.stats.dbBytes / 1e6).toFixed(0) : '-'} | ${row.load ? row.load.bytesPerTriple.toFixed(0) : '-'} |`,
  );
}
console.log('\n' + tables.join('\n'));
