// Regenerates `../avatar-images.ts` from the WebP headshots in this directory (run with `node avatars/generate.mjs`).
// Each headshot is a 128×128 WebP named after the person (`omar-haddad.webp`); 128px covers a 64px avatar at 2×.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** File slug to the person's full name, where the slug drops a diacritic the name keeps. */
const NAMES = {
  'tomas-vidal': 'Tomás Vidal',
};

const toName = (slug) =>
  NAMES[slug] ??
  slug
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join(' ');

const dir = dirname(fileURLToPath(import.meta.url));
const entries = readdirSync(dir)
  .filter((file) => file.endsWith('.webp'))
  .sort()
  .map((file) => {
    const data = readFileSync(join(dir, file)).toString('base64');
    return `  '${toName(basename(file, '.webp'))}': 'data:image/webp;base64,${data}',`;
  });

writeFileSync(
  join(dir, '..', 'avatar-images.ts'),
  [
    '//',
    '// Copyright 2026 DXOS.org',
    '//',
    '',
    '// Generated by `avatars/generate.mjs` from the WebP headshots in `avatars/`; do not edit by hand.',
    '',
    '/** Headshots by full name, as data URLs (`Person.image` is a URL). */',
    'export const AVATAR_IMAGES: Readonly<Record<string, string>> = {',
    ...entries,
    '};',
    '',
  ].join('\n'),
);
