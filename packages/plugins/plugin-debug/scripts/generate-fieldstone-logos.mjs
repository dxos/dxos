// Regenerates `src/samples/fieldstone/logo-images.ts` from the WebP posters in `src/samples/fieldstone/logos/` (run with `node scripts/generate-fieldstone-logos.mjs` from the package).
// Each poster is a 480×270 (16:9) WebP padded from the original 5:4 logo with its own background colour.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const NAMES = {
  aldermoor: 'Aldermoor Bank',
  alienlabs: 'Alien Labs',
  brightwater: 'Brightwater Games',
  cloudflare: 'Cloudflare',
  corvid: 'Corvid Analytics',
  halcyon: 'Halcyon Freight',
  kestrel: 'Kestrel Energy',
  larkspur: 'Larkspur Media',
  lumen: 'Lumen Biotech',
  meridian: 'Meridian Health Data',
  northpine: 'Northpine Robotics',
  okapi: 'Okapi Payments',
  pallas: 'Pallas Retail Group',
  tidewater: 'Tidewater Insurance',
  vantage: 'Vantage Aerospace',
};

const samples = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'samples', 'fieldstone');
const dir = join(samples, 'logos');
const entries = readdirSync(dir)
  .filter((file) => file.endsWith('.webp'))
  .sort()
  .map((file) => {
    const name = NAMES[basename(file, '.webp')];
    if (!name) {
      throw new Error(`No organization for ${file}`);
    }
    const data = readFileSync(join(dir, file)).toString('base64');
    return `  '${name}': 'data:image/webp;base64,${data}',`;
  });

writeFileSync(
  join(samples, 'logo-images.ts'),
  [
    '//',
    '// Copyright 2026 DXOS.org',
    '//',
    '',
    '// Generated by `scripts/generate-fieldstone-logos.mjs` from the WebP posters in `logos/`; do not edit by hand.',
    '',
    '/** Logo posters by organization name, as data URLs (`Organization.image` is a URL). */',
    'export const LOGO_IMAGES: Readonly<Record<string, string>> = {',
    ...entries,
    '};',
    '',
  ].join('\n'),
);
