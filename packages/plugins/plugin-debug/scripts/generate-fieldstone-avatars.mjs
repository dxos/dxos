// Regenerates `src/samples/fieldstone/avatar-images.ts` from the WebP headshots in `src/samples/fieldstone/avatars/` (run with `node scripts/generate-fieldstone-avatars.mjs` from the package).
// Each headshot is a 240×240 WebP named after the person (`omar-haddad.webp`); 240px covers the 120px card photo at 2×.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** File slug to the person's full name, where the slug drops a diacritic the name keeps. */
const NAMES = {
  'ines-duarte': 'Inês Duarte',
  'lucia-ferreira': 'Lucía Ferreira',
  'tomas-vidal': 'Tomás Vidal',
};

const toName = (slug) =>
  NAMES[slug] ??
  slug
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join(' ');

const samples = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'samples', 'fieldstone');
const dir = join(samples, 'avatars');
const entries = readdirSync(dir)
  .filter((file) => file.endsWith('.webp'))
  .sort()
  .map((file) => {
    const data = readFileSync(join(dir, file)).toString('base64');
    return `  '${toName(basename(file, '.webp'))}': 'data:image/webp;base64,${data}',`;
  });

writeFileSync(
  join(samples, 'avatar-images.ts'),
  [
    '//',
    '// Copyright 2026 DXOS.org',
    '//',
    '',
    '// Generated by `scripts/generate-fieldstone-avatars.mjs` from the WebP headshots in `avatars/`; do not edit by hand.',
    '',
    '/** Headshots by full name, as data URLs (`Person.image` is a URL). */',
    'export const AVATAR_IMAGES: Readonly<Record<string, string>> = {',
    ...entries,
    '};',
    '',
  ].join('\n'),
);
