// Bundles the dialect files in `lang/` as `src/schema/gen/dialects.ts`, so the schemas they declare resolve without a file system.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The module text for the dialect files in `lang/`, keyed by frontmatter id; the plugin template is not a dialect. */
export const dialectModule = (dir = join(root, 'lang')) => {
  const entries = readdirSync(dir)
    .filter((file) => file.endsWith('.mdl') && !file.includes('template'))
    .sort()
    .map((file) => {
      const text = readFileSync(join(dir, file), 'utf8');
      const id = text.match(/^---\n[\s\S]*?^id:[ \t]*(\S+)/m)?.[1];
      return [id, text];
    })
    .filter(([id]) => id);
  return [
    '//',
    '// Copyright 2026 DXOS.org',
    '//',
    '',
    '// Generated by scripts/gen-dialects.mjs from lang/*.mdl; do not edit.',
    '',
    'export const DIALECT_SOURCES: Readonly<Record<string, string>> = {',
    ...entries.map(([id, text]) => `  ${JSON.stringify(id)}: ${JSON.stringify(text)},`),
    '};',
    '',
  ].join('\n');
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, 'src/schema/gen/dialects.ts'), dialectModule());
}
