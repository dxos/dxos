// Writes the DEUS Worker's generated modules (D192): `gen/explorer-app.mjs`, the explorer app's files as
// strings, and with `--live` also `gen/explorer-live.js`, the explorer's DEUS code compiled to JS from
// the codebase (`deus build --js`). Run it before `wrangler deploy`; `src/live-explorer.test.ts` fails
// when the app module is behind `platform/explorer/`.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const gen = join(root, 'platform/worker/gen');

/** The app's files, as `deus explore` copies them (`Explorer.appFiles`). */
export const APP_FILES = ['index.html', 'app.js', 'app.css'];

export const appModule = () =>
  [
    '// Generated by `scripts/build-worker.mjs` from `platform/explorer/`. Edit those files, not this one.',
    '',
    `export const appFiles = ${JSON.stringify(
      Object.fromEntries(APP_FILES.map((name) => [name, readFileSync(join(root, 'platform/explorer', name), 'utf8')])),
    )};`,
    '',
  ].join('\n');

if (import.meta.main ?? process.argv[1] === import.meta.filename) {
  writeFileSync(join(gen, 'explorer-app.mjs'), appModule());
  if (process.argv.includes('--live')) {
    execFileSync(
      'node',
      [
        join(root, 'bin/deus.mjs'),
        'build',
        'Explorer.site',
        'Explorer.liveIndex',
        'Explorer.liveDef',
        'Explorer.liveChange',
        '-o',
        join(gen, 'explorer-live.js'),
        '--js',
      ],
      { stdio: 'inherit' },
    );
  }
}
