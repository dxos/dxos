// Writes the DEUS Worker's generated modules (D192): `gen/explorer-app.mjs`, the explorer app's files as
// strings, and with `--live` also `gen/explorer-live.js`, `gen/address.js` and `gen/packs.js`, DEUS code compiled to JS from
// the codebase (`deus build --js`). Run it before `wrangler deploy`; `src/live-explorer.test.ts` fails
// when the app module is behind `platform/explorer/`.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const gen = join(root, 'platform/worker/gen');

/** The app's files, as `deus explore` copies them (`Explorer.appFiles`). */
export const APP_FILES = ['index.html', 'app.js', 'app.css'];

/** The todo app's built files, which the Worker serves at /demo/todo/. */
export const DEMO_FILES = ['index.html', 'app.css', 'bundle.js'];

/** The host's front page (D200), which only the Worker serves. */
export const HUB_FILES = ['hub.html', 'hub.js'];

export const appModule = () =>
  [
    '// Generated by `scripts/build-worker.mjs` from `platform/explorer/`. Edit those files, not this one.',
    '',
    `export const appFiles = ${JSON.stringify(
      Object.fromEntries(APP_FILES.map((name) => [name, readFileSync(join(root, 'platform/explorer', name), 'utf8')])),
    )};`,
    '',
    `export const hubFiles = ${JSON.stringify(
      Object.fromEntries(HUB_FILES.map((name) => [name, readFileSync(join(root, 'platform/explorer', name), 'utf8')])),
    )};`,
    '',
  ].join('\n');

if (import.meta.main ?? process.argv[1] === import.meta.filename) {
  writeFileSync(join(gen, 'explorer-app.mjs'), appModule());
  if (process.argv.includes('--live')) {
    execFileSync(
      'node',
      [
        join(root, 'bin/deus.mjs'),
        'build',
        'Explorer.site',
        'Explorer.liveIndex',
        'Explorer.liveDef',
        'Explorer.liveChange',
        'Explorer.liveDoc',
        '-o',
        join(gen, 'explorer-live.js'),
        '--js',
      ],
      { stdio: 'inherit' },
    );
    execFileSync(
      'node',
      [
        join(root, 'bin/deus.mjs'),
        'build',
        'Address.projectAt',
        'Address.addressOfFolder',
        'Address.isGrantable',
        'Address.grants',
        '-o',
        join(gen, 'address.js'),
        '--js',
      ],
      { stdio: 'inherit' },
    );
    // The Worker's own DEUS code (`platform/worker/deus/`), from the `@dxos/worker` codebase, which mounts the
    // toolchain and `@dxos/web` (for `Js`); `deus pull` it into `$DEUS_WORKER_CODEBASE` (default ~/.deus-worker).
    const workerCodebase = process.env.DEUS_WORKER_CODEBASE ?? join(homedir(), '.deus-worker');
    if (existsSync(workerCodebase)) {
      execFileSync(
        'node',
        [
          join(root, 'bin/deus.mjs'),
          'build',
          'Worker.Packs.parseRange',
          'Worker.Packs.checkIndex',
          'Worker.Packs.checkCombined',
          'Worker.Packs.combinedFanout',
          'Worker.Packs.search',
          'Worker.Packs.newestAt',
          '-o',
          join(gen, 'packs.js'),
          '--js',
        ],
        { stdio: 'inherit', env: { ...process.env, DEUS_CODEBASE: workerCodebase } },
      );
      execFileSync(
        'node',
        [
          join(root, 'bin/deus.mjs'),
          'build',
          'Worker.Heads.parseClaim',
          'Worker.Heads.isBranch',
          'Worker.Heads.verdict',
          '-o',
          join(gen, 'heads.js'),
          '--js',
        ],
        { stdio: 'inherit', env: { ...process.env, DEUS_CODEBASE: workerCodebase } },
      );
    } else {
      console.warn(
        `no @dxos/worker codebase at ${workerCodebase}, so gen/packs.js and gen/heads.js are left as they are`,
      );
    }
    // The todo app (examples/react), built as `examples/react/build.sh` builds it and served at /demo/todo/,
    // so a visitor sees DEUS components running beside their source.
    const out = mkdtempSync(join(tmpdir(), 'deus-demo-'));
    try {
      execFileSync('bash', [join(root, 'examples/react/build.sh'), out], {
        stdio: 'inherit',
        env: { ...process.env, DEUS_REACT_ENV: 'production', DEUS_CODEBASE: join(out, 'codebase') },
      });
      const files = Object.fromEntries(DEMO_FILES.map((name) => [name, readFileSync(join(out, name), 'utf8')]));
      writeFileSync(
        join(gen, 'demo-todo.mjs'),
        `// Generated by \`scripts/build-worker.mjs --live\` from examples/react. Edit those files, not this one.\n\nexport const demoFiles = ${JSON.stringify(files)};\n`,
      );
    } finally {
      rmSync(out, { recursive: true, force: true });
    }
  }
}
