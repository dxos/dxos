// Writes `src/phosphor.ts` from the Phosphor package's own regular assets, so the catalogue the icon picker offers
// is the set the icon registry can actually resolve (`/phosphor/regular/<name>.svg`) rather than a hand-kept list.
// Run through the package's `prebuild-phosphor` task.
//

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

/** The package exports no `package.json`, so its assets are found by walking up to the workspace root. */
const findAssets = () => {
  for (let dir = here; dir !== dirname(dir); dir = dirname(dir)) {
    const assets = join(dir, 'node_modules/@phosphor-icons/core/assets/regular');
    if (existsSync(assets)) {
      return assets;
    }
  }
  throw new Error('@phosphor-icons/core is not installed.');
};

const assets = findAssets();

const names = readdirSync(assets)
  .filter((file) => file.endsWith('.svg'))
  .map((file) => file.slice(0, -'.svg'.length))
  .sort();

const out = join(here, '../src/phosphor.ts');
const source = `//
// Copyright 2026 DXOS.org
//

//
// GENERATED by scripts/gen-phosphor.mjs — do not edit.
//
// Every regular Phosphor glyph, by bare name (\`acorn\` draws as \`ph--acorn--regular\`). The icon registry fetches a
// symbol the sprite does not hold, so each of these renders without being named anywhere in source; this list exists
// so a picker can offer them. ${names.length} names.
//

export const phosphorIcons: readonly string[] = [
${names.map((name) => `  '${name}',`).join('\n')}
];
`;

const previous = (() => {
  try {
    return readFileSync(out, 'utf8');
  } catch {
    return undefined;
  }
})();

if (previous !== source) {
  writeFileSync(out, source);
}

console.log(`phosphor: ${names.length} icons`);
