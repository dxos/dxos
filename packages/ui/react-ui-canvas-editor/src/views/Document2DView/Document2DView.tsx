import React, { type PropsWithChildren, useCallback, useMemo, useState } from 'react';

import { type Camera, type NodeRegistry } from '@dxos/react-ui-canvas';
import { type LayoutIntent, type Scene, applyIntent } from '@dxos/scene';

import { createConfig2D } from '../../dimensions/index.ts';
import { type EditorDisplay, SceneEditor } from '../../editor/index.ts';

/** The camera the camera bar resets to: the origin at 1:1. */
const AUTHORED_CAMERA: Camera = { x: 0, y: 0, zoom: 1 };

/** Applies `intent` to layout `key`; a layout the document does not hold takes nothing. */
const applyLayout = (document: Scene.SceneDocument, key: string, intent: LayoutIntent): Scene.SceneDocument => {
  const existing = document.layouts.find((layout) => layout.id === key);
  const next = existing && applyIntent(existing, intent);
  return !next || next === existing
    ? document
    : { ...document, layouts: document.layouts.map((layout) => (layout.id === key ? next : layout)) };
};

export type Document2DViewProps = PropsWithChildren<{
  /** The document drawn, from its first scene; a new one replaces every move made in the view. */
  document: Scene.SceneDocument;
  /** The node types the viewport draws (a host's cards among them). */
  nodes?: NodeRegistry;
  /** Whether the background grid is drawn. */
  grid?: boolean;
  /** Whether a lattice's cells are drawn; off for a lattice too fine to read as places. */
  guides?: boolean;
}>;

/**
 * A 2D document generated by its host, in the shared scene editor: shapes move (snapped by each layout's mode) and
 * frames drill into the scenes they show, with the drill path as breadcrumbs. Moves are kept in memory, not written
 * back. Children float over the viewport.
 */
export const Document2DView = ({ document, nodes, grid = false, guides = true, children }: Document2DViewProps) => {
  const [moved, setMoved] = useState({ document, drawn: document });
  const drawn = moved.document === document ? moved.drawn : document;
  const handleIntent = useCallback(
    (layout: string, intent: LayoutIntent) =>
      setMoved((current) => {
        const base = current.document === document ? current.drawn : document;
        return { document, drawn: applyLayout(base, layout, intent) };
      }),
    [document],
  );
  const config = useMemo(() => createConfig2D({ nodes, capabilities: { move: true } }), [nodes]);
  const [display, setDisplay] = useState<EditorDisplay>({ theme: 'flat', grid, snap: true, guides });
  const handleDisplayChange = useCallback(
    (next: Partial<EditorDisplay>) => setDisplay((current) => ({ ...current, ...next })),
    [],
  );
  const [camera, setCamera] = useState<Camera>();

  return (
    <SceneEditor.Root
      config={config}
      document={drawn}
      scene={drawn.scenes[0]?.id ?? ''}
      onIntent={handleIntent}
      display={display}
      onDisplayChange={handleDisplayChange}
      camera={camera}
      authoredCamera={AUTHORED_CAMERA}
      onCameraChange={setCamera}
    >
      <SceneEditor.Viewport>
        <SceneEditor.Navigation />
        <SceneEditor.Camera />
        {children}
      </SceneEditor.Viewport>
    </SceneEditor.Root>
  );
};
